const { format } = require('date-fns');

function replaceVariables(str, data) {
    const variables = {
        '{guild.name}': data.guild?.name,
        '{guild.id}': data.guild?.id,
        '{guild.count}': data.guild?.memberCount,
        '{guild.region}': data.guild?.region,
        '{guild.shard}': data.guild?.shardId,
        '{guild.owner_id}': data.guild?.ownerId,
        '{guild.created_at}': data.guild?.createdAt?.toUTCString(),
        '{guild.created_at_timestamp}': data.guild?.createdAt?.getTime(),
        '{guild.emoji_count}': data.guild?.emojis?.cache?.size,
        '{guild.role_count}': data.guild?.roles?.cache?.size,
        '{guild.boost_count}': data.guild?.premiumSubscriptionCount,
        '{guild.boost_tier}': data.guild?.premiumTier,
        '{guild.preferred_locale}': data.guild?.preferredLocale,
        '{guild.key_features}': data.guild?.features?.join(', '),
        '{guild.icon}': data.guild?.iconURL({ format: data.guild?.icon?.startsWith('a_') ? 'gif' : 'png' }),
        '{guild.banner}': data.guild?.bannerURL({ format: data.guild?.banner?.startsWith('a_') ? 'gif' : 'png' }),
        '{guild.splash}': data.guild?.splashURL({ format: data.guild?.splash?.startsWith('a_') ? 'gif' : 'png' }),
        '{guild.discovery}': data.guild?.discoverySplashURL({ format: data.guild?.discoverySplash?.startsWith('a_') ? 'gif' : 'png' }),
        '{guild.max_presences}': data.guild?.maxPresences,
        '{guild.max_members}': data.guild?.maxMembers,
        '{guild.max_video_channel_users}': data.guild?.maxVideoChannelUsers,
        '{guild.afk_timeout}': data.guild?.afkTimeout,
        '{guild.afk_channel}': data.guild?.afkChannel?.name,
        '{guild.channels}': data.guild?.channels?.cache?.map(ch => ch.name).join(', '),
        '{guild.channels_count}': data.guild?.channels?.cache?.size,
        '{guild.text_channels}': data.guild?.channels?.cache?.filter(ch => ch.type === 'GUILD_TEXT').map(ch => ch.name).join(', '),
        '{guild.text_channels_count}': data.guild?.channels?.cache?.filter(ch => ch.type === 'GUILD_TEXT').size,
        '{guild.voice_channels}': data.guild?.channels?.cache?.filter(ch => ch.type === 'GUILD_VOICE').map(ch => ch.name).join(', '),
        '{guild.voice_channels_count}': data.guild?.channels?.cache?.filter(ch => ch.type === 'GUILD_VOICE').size,
        '{guild.category_channels}': data.guild?.channels?.cache?.filter(ch => ch.type === 'GUILD_CATEGORY').map(ch => ch.name).join(', '),
        '{guild.category_channels_count}': data.guild?.channels?.cache?.filter(ch => ch.type === 'GUILD_CATEGORY').size,

        '{user}': `${data.user?.username}#${data.user?.discriminator}`,
        '{user.id}': data.user?.id,
        '{user.mention}': `<@${data.user?.id}>`,
        '{user.name}': data.user?.username,
        '{user.tag}': data.user?.discriminator,
        '{user.avatar}': data.user?.avatarURL({ format: data.user?.avatar?.startsWith('a_') ? 'gif' : 'png' }),
        '{user.guild_avatar}': data.member?.displayAvatarURL({ format: data.member?.avatar?.startsWith('a_') ? 'gif' : 'png' }),
        '{user.display_avatar}': data.user?.displayAvatarURL({ format: data.user?.avatar?.startsWith('a_') ? 'gif' : 'png' }),
        '{user.joined_at}': data.member?.joinedAt?.toUTCString(),
        '{user.joined_at_timestamp}': data.member?.joinedAt?.getTime(),
        '{user.created_at}': data.user?.createdAt?.toUTCString(),
        '{user.created_at_timestamp}': data.user?.createdAt?.getTime(),
        '{user.display_name}': data.member?.displayName,
        '{user.boost}': data.member?.premiumSince ? 'Yes' : 'No',
        '{user.boost_since}': data.member?.premiumSince?.toUTCString(),
        '{user.boost_since_timestamp}': data.member?.premiumSince?.getTime(),
        '{user.color}': data.member?.displayHexColor,
        '{user.top_role}': data.member?.roles?.highest?.name,
        '{user.role_list}': data.member?.roles?.cache?.map(role => role.name).join(', '),
        '{user.role_text_list}': data.member?.roles?.cache?.map(role => role.name).join(', '),
        '{user.bot}': data.user?.bot ? 'Yes' : 'No',
        '{user.badges_icons}': data.user?.flags?.toArray().map(flag => flag).join(', '),
        '{user.badges}': data.user?.flags?.toArray().map(flag => flag).join(', '),
        '{user.join_position}': data.member?.joinPosition,
        '{user.join_position_suffix}': data.member?.joinPosition,

        '{channel.name}': data.channel?.name,
        '{channel.id}': data.channel?.id,
        '{channel.mention}': `<#${data.channel?.id}>`,
        '{channel.topic}': data.channel?.topic,
        '{channel.type}': data.channel?.type,
        '{channel.category_id}': data.channel?.parentId,
        '{channel.category_name}': data.channel?.parent?.name,
        '{channel.position}': data.channel?.position,
        '{channel.slowmode_delay}': data.channel?.rateLimitPerUser,

        '{date.now}': format(new Date(), 'PST'),
        '{date.utc_timestamp}': Math.floor(Date.now() / 1000),
        '{date.now_proper}': format(new Date(), 'PPPPpppp'),
        '{date.now_short}': format(new Date(), 'P'),
        '{date.now_shorter}': format(new Date(), 'Pp'),
        '{time.now}': format(new Date(), 'hh:mm a'),
        '{time.now_military}': format(new Date(), 'HH:mm'),
        '{date.utc_now}': new Date().toUTCString(),
        '{date.utc_now_proper}': format(new Date(), 'PPPPpppp', { timeZone: 'UTC' }),
        '{date.utc_now_short}': format(new Date(), 'P', { timeZone: 'UTC' }),
        '{date.utc_now_shorter}': format(new Date(), 'Pp', { timeZone: 'UTC' }),
        '{time.utc_now}': format(new Date(), 'hh:mm a', { timeZone: 'UTC' }),
        '{time.utc_now_military}': format(new Date(), 'HH:mm', { timeZone: 'UTC' }),
    };

    return str.replace(/{[^}]+}/g, match => variables[match] || match);
}

module.exports = { replaceVariables };